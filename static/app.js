// Paper page: pull the detailed summary in after paint, then run the chat.
(function () {
  "use strict";

  const grid = document.querySelector(".paper-grid");
  if (!grid) return;

  const paperId = grid.dataset.paperId;
  // Old-style ids (math/0309136) contain a slash that is part of the path, so
  // each segment is escaped separately rather than encoding the whole id.
  const idPath = paperId.split("/").map(encodeURIComponent).join("/");

  async function readError(response) {
    try {
      const body = await response.json();
      if (body && body.error) return body.error;
    } catch (_) {
      /* fall through to the status line */
    }
    return `Request failed (${response.status} ${response.statusText}).`;
  }

  // --- detailed summary ---------------------------------------------

  const summary = document.getElementById("summary");

  async function loadSummary() {
    if (!summary) return;
    try {
      const response = await fetch(`/api/summary/${idPath}`);
      if (!response.ok) throw new Error(await readError(response));

      const body = await response.json();
      if (!body.available) {
        summary.innerHTML = "";
        summary.append(note("Summaries are disabled — no OPENAI_API_KEY is configured."));
        summary.dataset.state = "disabled";
        return;
      }

      summary.innerHTML = body.html;
      summary.dataset.state = "ready";

      const credit = document.createElement("p");
      credit.className = "chat-hint";
      credit.textContent = `Generated by ${body.model} from the paper's full text.`;
      summary.after(credit);
    } catch (err) {
      summary.innerHTML = "";
      summary.append(note(`Could not summarize this paper. ${err.message}`));
      summary.dataset.state = "error";
    }
  }

  function note(text) {
    const el = document.createElement("p");
    el.className = "error-box";
    el.textContent = text;
    return el;
  }

  // --- chat ----------------------------------------------------------

  const form = document.getElementById("chat-form");
  const input = document.getElementById("chat-input");
  const log = document.getElementById("chat-log");
  const history = [];

  function bubble(kind, content, isHtml) {
    const el = document.createElement("div");
    el.className = `bubble bubble-${kind}`;
    if (isHtml) {
      el.innerHTML = content;
    } else {
      el.textContent = content;
    }
    log.append(el);
    el.scrollIntoView({ block: "nearest", behavior: "smooth" });
    return el;
  }

  async function send(question) {
    bubble("user", question, false);
    history.push({ role: "user", content: question });

    const pending = bubble("assistant", "Thinking…", false);
    const button = form.querySelector("button");
    button.disabled = true;

    try {
      const response = await fetch(`/api/chat/${idPath}`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ messages: history }),
      });
      if (!response.ok) throw new Error(await readError(response));

      const body = await response.json();
      pending.innerHTML = body.html;
      history.push({ role: "assistant", content: body.reply });
    } catch (err) {
      pending.className = "bubble bubble-error";
      pending.textContent = err.message;
      // Drop the unanswered turn so the next question isn't sent with a hole in it.
      history.pop();
    } finally {
      button.disabled = false;
      input.focus();
    }
  }

  if (form) {
    form.addEventListener("submit", (event) => {
      event.preventDefault();
      const question = input.value.trim();
      if (!question) return;
      input.value = "";
      send(question);
    });

    input.addEventListener("keydown", (event) => {
      if (event.key === "Enter" && !event.shiftKey) {
        event.preventDefault();
        form.requestSubmit();
      }
    });
  }

  loadSummary();
})();
